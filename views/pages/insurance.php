<script>
document.addEventListener('DOMContentLoaded', function() {
    const duration = document.getElementById('rental_duration');
    const coverage = document.getElementById('coverage_type');
    
    const rates = {
        none: 0,
        basic: 15,
        premium: 25,
        full: 35
    };
    
    function calculateInsurance() {
        const dailyRate = rates[coverage.value];
        const totalCost = dailyRate * duration.value;
        
        document.getElementById('daily-rate').textContent = '$' + dailyRate.toFixed(2);
        document.getElementById('total-cost').textContent = '$' + totalCost.toFixed(2);
    }
    
    duration.addEventListener('input', calculateInsurance);
    coverage.addEventListener('change', calculateInsurance);
    
    calculateInsurance();
});
</script> 